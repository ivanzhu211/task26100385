// Package langstat 提供只读的仓库语言统计。
//
// 调用方通过 Analyze 传入本地源码目录，库按目录内嵌套的 .gitignore
// 规则确定分析范围，统计 .py/.js/.ts/.go 文件的字节量与占比，
// 结果保存在内存中。不依赖 Git 程序或 .git 目录，
// 文件是否被版本控制跟踪不影响统计。
//
// 规则语义：
//   - 每个目录的 .gitignore 仅作用于该目录及其后代；
//     祖先规则先应用，同文件内后面的规则覆盖前面的规则。
//   - 末尾 / 仅匹配目录；含 / 的规则相对于所在目录锚定；
//     不含 / 的规则匹配任意深度的文件名或目录名。
//   - * ? [...] 不跨斜杠；完整 ** 段匹配零层或多层目录；
//     末尾 /** 匹配目录内所有层级条目但不匹配目录本身。
//   - 被排除的目录屏蔽其全部后代，其内部 .gitignore 不参与判断；
//     未排除的目录即使忽略自身 .gitignore 也照常读取。
//
// Explain 可解释任一现存文件为何被计入或排除；
// 被祖先目录屏蔽时指向该祖先的排除规则。
